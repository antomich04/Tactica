export type TranslationKey = keyof typeof TRANSLATIONS.en;

export function useTranslation() {
  const { user } = useAuth();
  const savedLang = (typeof window !== "undefined"
    ? window.localStorage.getItem(LANG_STORAGE_KEY)
    : null) as LanguageCode | null;

  const lang: LanguageCode =
    user?.preferences?.language ||
    (savedLang && savedLang in TRANSLATIONS ? savedLang : "en");

  if (typeof window !== "undefined" && user?.preferences?.language) {
    window.localStorage.setItem(LANG_STORAGE_KEY, user.preferences.language);
  }

  const dict = TRANSLATIONS[lang] ?? TRANSLATIONS.en;

  const t = (key: TranslationKey, vars?: Record<string, string | number>): string => {
    let text: string = dict[key] ?? TRANSLATIONS.en[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        text = text.replace(`{${k}}`, String(v));
      }
    }
    return text;
  };

  return { t, lang };
}